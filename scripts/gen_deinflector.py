#!/usr/bin/env python3
"""Generate Java deinflection rules from hoshidicts' C++ rule table.

Source: https://github.com/Manhhao/hoshidicts (shallow-cloned at ../hoshidicts)
hoshidicts adopts Yomitan's Japanese transforms; only the rule data is copied here.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "hoshidicts" / "src" / "deinflector.cpp"
OUT = ROOT / "jepubvocab" / "java" / "com" / "buddyapps" / "jepubvocab" / "DeinflectorRules.java"

CONDS = {
    "NONE": 0, "V1D": 1 << 0, "V1P": 1 << 1, "V5D": 1 << 2,
    "V5SS": 1 << 3, "V5SP": 1 << 4, "VK": 1 << 5, "VS": 1 << 6,
    "VZ": 1 << 7, "ADJ_I": 1 << 8, "MASU": 1 << 9, "MASEN": 1 << 10,
    "TE": 1 << 11, "BA": 1 << 12, "KU": 1 << 13, "TA": 1 << 14,
    "NN": 1 << 15, "NASAI": 1 << 16, "YA": 1 << 17,
}
CONDS["V1"] = CONDS["V1D"] | CONDS["V1P"]
CONDS["V5S"] = CONDS["V5SS"] | CONDS["V5SP"]
CONDS["V5"] = CONDS["V5D"] | CONDS["V5S"]
CONDS["V"] = CONDS["V1"] | CONDS["V5"] | CONDS["VK"] | CONDS["VS"] | CONDS["VZ"]


def balanced(text, start):
    """Return (content, index after closing paren) for a call at `start`."""
    depth = 0
    i = text.index("(", start)
    quoted = None
    while i < len(text):
        c = text[i]
        if quoted:
            if c == "\\":
                i += 2
                continue
            if c == quoted:
                quoted = None
        elif c in "\"'":
            quoted = c
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return text[text.index("(", start) + 1:i], i + 1
        i += 1
    raise ValueError("unbalanced call")


def cond(expr):
    expr = expr.strip()
    for name, value in sorted(CONDS.items(), key=lambda kv: -len(kv[0])):
        expr = re.sub(r"\b" + name + r"\b", str(value), expr)
    return int(eval(expr, {"__builtins__": {}}, {}))


def cstr(value):
    return json.dumps(value, ensure_ascii=True)


text = SRC.read_text(encoding="utf-8")
body_start = text.index("void Deinflector::init_transforms()")
body_end = text.index("int Deinflector::add_group", body_start)
body = text[body_start:body_end]

groups = []
rules = []
current_group = -1
iques = [("いく", "いっ"), ("行く", "行っ"), ("逝く", "逝っ"), ("往く", "往っ")]
godan_u = ["こう", "とう", "請う", "乞う", "恋う", "問う", "訪う", "宣う", "曰う", "給う", "賜う", "揺蕩う"]
fu = [("のたまう", "のたもう"), ("たまう", "たもう"), ("たゆたう", "たゆとう")]

i = 0
while i < len(body):
    m = re.search(r"add_(group|rule|irregular)\s*\(", body[i:])
    if not m:
        break
    pos = i + m.start()
    kind = m.group(1)
    args, i = balanced(body, pos)
    if kind == "group":
        name = re.search(r'\.name\s*=\s*"((?:[^"\\]|\\.)*)"', args)
        groups.append(json.loads('"' + name.group(1) + '"') if name else "")
        current_group = len(groups) - 1
    elif kind == "rule":
        frm = re.search(r'\.from\s*=\s*"((?:[^"\\]|\\.)*)"', args)
        to = re.search(r'\.to\s*=\s*"((?:[^"\\]|\\.)*)"', args)
        cin = re.search(r"\.conditions_in\s*=\s*([^,]+)", args)
        cout = re.search(r"\.conditions_out\s*=\s*([^,]+)", args)
        gid = re.search(r"\.group_id\s*=\s*([^,}]+)", args)
        rules.append((
            json.loads('"' + frm.group(1) + '"'),
            json.loads('"' + to.group(1) + '"'),
            cond(cin.group(1)), cond(cout.group(1)),
            current_group if not gid or gid.group(1).strip() == "id"
            else int(gid.group(1)),
        ))
    else:
        parts = []
        for part in re.finditer(r'"((?:[^"\\]|\\.)*)"|[A-Za-z_][A-Za-z0-9_|]*|-?\d+', args):
            token = part.group(0)
            parts.append(json.loads('"' + part.group(1) + '"') if token.startswith('"') else token)
        suffix = parts[0]
        cin, cout, gid = cond(parts[1]), cond(parts[2]), current_group
        for verb, prefix in iques:
            rules.append((prefix + suffix, verb, cin, cout, gid))
        for verb in godan_u:
            rules.append((verb + suffix, verb, cin, cout, gid))
        for verb, root in fu:
            rules.append((root + suffix, verb, cin, cout, gid))

lines = [
    "// Generated by scripts/gen_deinflector.py from hoshidicts (Manhhao/hoshidicts),",
    "// which adopts Yomitan's Japanese deinflection rules. Do not edit by hand.",
    "package com.buddyapps.jepubvocab;",
    "",
    "final class DeinflectorRules {",
    "    private DeinflectorRules() { }",
    "",
    "    static final int NONE = 0;",
]
for name in ["V1D", "V1P", "V5D", "V5SS", "V5SP", "VK", "VS", "VZ", "ADJ_I",
             "MASU", "MASEN", "TE", "BA", "KU", "TA", "NN", "NASAI", "YA"]:
    lines.append("    static final int %s = %d;" % (name, CONDS[name]))
for name in ["V1", "V5S", "V5", "V"]:
    lines.append("    static final int %s = %d;" % (name, CONDS[name]))
lines += ["", "    static final String[] GROUPS = {"]
lines += ["        " + cstr(g) + "," for g in groups]
lines += ["    };", "", "    static final Rule[] RULES = {"]
for frm, to, cin, cout, gid in rules:
    lines.append("        new Rule(%s, %s, %d, %d, %d)," % (cstr(frm), cstr(to), cin, cout, gid))
lines += [
    "    };",
    "",
    "    static final class Rule {",
    "        final String from, to;",
    "        final int conditionsIn, conditionsOut, group;",
    "        Rule(String from, String to, int conditionsIn, int conditionsOut, int group) {",
    "            this.from = from;",
    "            this.to = to;",
    "            this.conditionsIn = conditionsIn;",
    "            this.conditionsOut = conditionsOut;",
    "            this.group = group;",
    "        }",
    "    }",
    "}",
]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("groups=%d rules=%d -> %s (%d bytes)" % (len(groups), len(rules), OUT, OUT.stat().st_size))
